// Writes worker/app-routes.js: every page of the Expo app (app/src/app), as
// URL patterns the website's Worker (worker/routing.js) recognises, so it
// knows which addresses are the app's. Run after adding or moving a screen:
//   node scripts/build-app-routes.mjs
// tests/site-routing.test.js fails while the list is out of date.
import { readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const appDir = join(root, "app/src/app");

/** The app's routes as patterns: "/rituals/craft/cosmic/chart", "/coven/c/[slug]/book/[pageId]", "/more/covens/[...rest]". */
export function appRoutePatterns(dir = appDir) {
  const routes = new Set();
  const walk = (folder) => {
    for (const entry of readdirSync(folder, { withFileTypes: true })) {
      const full = join(folder, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (/\.tsx?$/.test(entry.name) && !/^[_+]/.test(entry.name) && !/\.(test|spec)\./.test(entry.name)) {
        const parts = relative(dir, full)
          .replace(/\.tsx?$/, "")
          .split(/[\\/]/)
          .filter((part) => !/^\(.*\)$/.test(part));
        if (parts[parts.length - 1] === "index") parts.pop();
        routes.add(`/${parts.join("/")}`);
      }
    }
  };
  walk(dir);
  return [...routes].sort();
}

export function appRoutesModule(routes = appRoutePatterns()) {
  return `// Generated by scripts/build-app-routes.mjs from app/src/app: do not edit.\nexport const APP_ROUTES = ${JSON.stringify(routes, null, 2)};\n`;
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) {
  const routes = appRoutePatterns();
  writeFileSync(join(root, "worker/app-routes.js"), appRoutesModule(routes));
  console.log(`worker/app-routes.js: ${routes.length} app routes`);
}
