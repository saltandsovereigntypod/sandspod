// Writes one entry per dedication journey, scripts/core/journey-<id>.ts, so
// scripts/build-core.mjs builds each journey's full text into its own small
// bundle (js/core/journey-<id>.js → window.SaltCore["journey-<id>"].journey)
// for the website to load only when that journey is opened. Run again when a
// journey is added, renamed or removed in app/src/lib/journeys/data:
//
//   node scripts/gen-journey-entries.mjs && node scripts/build-core.mjs
//
// Entries (and built bundles) for journeys that no longer exist are removed.

import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'app/src/lib/journeys/data');
const coreDir = join(root, 'scripts/core');

const wanted = new Map();
for (const file of readdirSync(dataDir).filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.startsWith('_')).sort()) {
  const text = readFileSync(join(dataDir, file), 'utf8');
  if (!/export const JOURNEY\b/.test(text)) continue;
  const id = /\bid:\s*['"]([^'"]+)['"]/.exec(text)?.[1] ?? file.replace(/\.ts$/, '');
  wanted.set(`journey-${id}`, file);
}

for (const f of readdirSync(coreDir)) {
  const name = f.replace(/\.ts$/, '');
  if (f.startsWith('journey-') && f.endsWith('.ts') && !wanted.has(name)) {
    rmSync(join(coreDir, f));
    const built = join(root, 'js/core', `${name}.js`);
    if (existsSync(built)) rmSync(built);
  }
}

for (const [name, file] of wanted) {
  writeFileSync(
    join(coreDir, `${name}.ts`),
    `// Generated by scripts/gen-journey-entries.mjs: one dedication journey's full text.\nexport { JOURNEY as journey } from '../../app/src/lib/journeys/data/${file}';\n`,
  );
}
console.log(`wrote ${wanted.size} journey entries to scripts/core`);
