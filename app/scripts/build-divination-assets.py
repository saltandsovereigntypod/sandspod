"""Build the app's copy of the website's tarot cards, in every deck.

The website keeps each deck's 78 cards as 600px-tall WebP: the
Rider-Waite-Smith (Pamela Colman Smith, 1909) in ../assets/divination/tarot,
the Tarot de Marseille (Nicolas Conver, 1760) and the Sola Busca (about 1491)
in ../assets/divination/decks/<deck>; all public domain, with every card's
source in app/assets/divination/decks/<deck>/SOURCES.md (and
../assets/divination/SOURCES.md for the Rider-Waite-Smith). The app bundles
them so draws work offline, packed seven across and two down on six sheets
a deck: an over-the-air update may carry at most 1000 files, and the altar's
pictures already come close. This writes src/lib/divination/tarotAssets.ts
with each card's sheet and place on it; components/divination/TarotArt.tsx
shows one card from its sheet.

Run from app/:  python3 scripts/build-divination-assets.py   (needs Pillow)
"""
import shutil
from pathlib import Path

from PIL import Image

APP = Path(__file__).resolve().parent.parent
SITE = APP.parent / "assets" / "divination"
MANIFEST = APP / "src" / "lib" / "divination" / "tarotAssets.ts"
CELL_W, CELL_H, COLS, ROWS = 350, 600, 7, 2

# deck id -> (the website's cards, where the app's sheets go)
DECKS = {
    "rws": (SITE / "tarot", APP / "assets" / "divination" / "tarot-sheets"),
    "marseille": (SITE / "decks" / "marseille", APP / "assets" / "divination" / "decks" / "marseille"),
    "sola-busca": (SITE / "decks" / "sola-busca", APP / "assets" / "divination" / "decks" / "sola-busca"),
}

old = APP / "assets" / "divination" / "tarot"
if old.exists():
    shutil.rmtree(old)

ids = [p.stem for p in sorted((SITE / "tarot").glob("*.webp"))]
assert len(ids) == 78, len(ids)
per = COLS * ROWS
sheets = {}
total = 0
for deck, (src, out) in DECKS.items():
    have = sorted(p.stem for p in src.glob("*.webp"))
    assert have == sorted(ids), f"{deck}: {len(have)} cards, or ids that aren't the deck's 78"
    out.mkdir(parents=True, exist_ok=True)
    for stale in out.glob("sheet-*.webp"):
        stale.unlink()
    names = []
    for s in range(0, len(ids), per):
        chunk = ids[s:s + per]
        sheet = Image.new("RGB", (COLS * CELL_W, ROWS * CELL_H), (233, 224, 204))
        for i, card in enumerate(chunk):
            im = Image.open(src / f"{card}.webp").convert("RGB").resize((CELL_W, CELL_H), Image.LANCZOS)
            sheet.paste(im, ((i % COLS) * CELL_W, (i // COLS) * CELL_H))
        name = f"sheet-{len(names) + 1}.webp"
        sheet.save(out / name, quality=84, method=6)
        names.append(name)
        total += (out / name).stat().st_size
    sheets[deck] = (out, names)

key = lambda deck: deck if deck.isidentifier() else f"'{deck}'"
lines = [
    "// Generated by scripts/build-divination-assets.py. Do not edit by hand.",
    "// Tarot card id (as in tarot.ts) to its sheet and place, in each deck: the app",
    "// bundles the website's card pictures packed onto six sheets a deck.",
    "",
    "import type { DeckId } from './decks';",
    "",
    f"export const TAROT_SHEET = {{ cols: {COLS}, rows: {ROWS}, cellWidth: {CELL_W}, cellHeight: {CELL_H} }} as const;",
    "",
    "const sheets: Record<DeckId, number[]> = {",
]
for deck, (out, names) in sheets.items():
    rel = out.relative_to(APP).as_posix()
    lines.append(f"  {key(deck)}: [")
    lines += [f"    require('../../../{rel}/{n}')," for n in names]
    lines.append("  ],")
lines += ["};", "", "export type TarotArtPlace = { sheet: number; col: number; row: number };", "",
          "export const deckImages: Record<DeckId, Record<string, TarotArtPlace>> = {"]
for deck in sheets:
    lines.append(f"  {key(deck)}: {{")
    ref = f"sheets.{deck}" if deck.isidentifier() else f"sheets['{deck}']"
    for k, card in enumerate(ids):
        i = k % per
        lines.append(f"    '{card}': {{ sheet: {ref}[{k // per}], col: {i % COLS}, row: {i // COLS} }},")
    lines.append("  },")
lines += ["};", "", "/** The Rider–Waite–Smith, the default deck. */", "export const tarotImages = deckImages.rws;", ""]
MANIFEST.write_text("\n".join(lines))
print(f"{len(ids)} cards in {len(sheets)} decks on {sum(len(n) for _, n in sheets.values())} sheets, {total / 1024 / 1024:.1f} MB")
