"""Build the app's copy of the website's tarot cards.

The website keeps the 78 Rider-Waite-Smith cards (Pamela Colman Smith, 1909,
public domain; see ../assets/divination/SOURCES.md) in ../assets/divination/tarot
as 600px-tall WebP. The app bundles them so draws work offline, packed seven
across and two down on six sheets: an over-the-air update may carry at most
1000 files, and the altar's pictures already come close. This writes
src/lib/divination/tarotAssets.ts with each card's sheet and place on it;
components/divination/TarotArt.tsx shows one card from its sheet.

Run from app/:  python3 scripts/build-divination-assets.py   (needs Pillow)
"""
import shutil
from pathlib import Path

from PIL import Image

APP = Path(__file__).resolve().parent.parent
SRC = APP.parent / "assets" / "divination" / "tarot"
OUT = APP / "assets" / "divination" / "tarot-sheets"
MANIFEST = APP / "src" / "lib" / "divination" / "tarotAssets.ts"
CELL_W, CELL_H, COLS, ROWS = 350, 600, 7, 2

old = APP / "assets" / "divination" / "tarot"
if old.exists():
    shutil.rmtree(old)
OUT.mkdir(parents=True, exist_ok=True)
for stale in OUT.glob("*.webp"):
    stale.unlink()

ids = [p.stem for p in sorted(SRC.glob("*.webp"))]
per = COLS * ROWS
sheets = []
for s in range(0, len(ids), per):
    chunk = ids[s:s + per]
    sheet = Image.new("RGB", (COLS * CELL_W, ROWS * CELL_H), (233, 224, 204))
    for i, card in enumerate(chunk):
        im = Image.open(SRC / f"{card}.webp").convert("RGB").resize((CELL_W, CELL_H), Image.LANCZOS)
        sheet.paste(im, ((i % COLS) * CELL_W, (i // COLS) * CELL_H))
    name = f"sheet-{len(sheets) + 1}.webp"
    sheet.save(OUT / name, quality=84, method=6)
    sheets.append(name)

lines = [
    "// Generated by scripts/build-divination-assets.py. Do not edit by hand.",
    "// Tarot card id (as in tarot.ts) to its sheet and place: the app bundles the",
    "// website's /assets/divination/tarot/<id>.webp packed onto a few sheets.",
    "",
    f"export const TAROT_SHEET = {{ cols: {COLS}, rows: {ROWS}, cellWidth: {CELL_W}, cellHeight: {CELL_H} }} as const;",
    "",
    "const sheets: number[] = [",
]
lines += [f"  require('../../../assets/divination/tarot-sheets/{n}'),"] if False else [f"  require('../../../assets/divination/tarot-sheets/{n}')," for n in sheets]
lines += ["];", "", "export type TarotArtPlace = { sheet: number; col: number; row: number };", "",
          "export const tarotImages: Record<string, TarotArtPlace> = {"]
for k, card in enumerate(ids):
    i = k % per
    lines.append(f"  '{card}': {{ sheet: sheets[{k // per}], col: {i % COLS}, row: {i // COLS} }},")
lines += ["};", ""]
MANIFEST.write_text("\n".join(lines))
total = sum((OUT / n).stat().st_size for n in sheets)
print(f"{len(ids)} cards on {len(sheets)} sheets, {total / 1024 / 1024:.1f} MB")
