"""Build the app's copy of the website's tarot cards.

The website keeps the 78 Rider-Waite-Smith cards (Pamela Colman Smith, 1909,
public domain; see ../assets/divination/SOURCES.md) in ../assets/divination/tarot
as 600px-tall WebP. The app bundles the same files so draws work offline, and
this writes src/lib/divination/tarotAssets.ts mapping each card's id to its copy.

Run from app/:  python3 scripts/build-divination-assets.py
"""
import shutil
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
SRC = APP.parent / "assets" / "divination" / "tarot"
OUT = APP / "assets" / "divination" / "tarot"
MANIFEST = APP / "src" / "lib" / "divination" / "tarotAssets.ts"

OUT.mkdir(parents=True, exist_ok=True)
ids = []
for path in sorted(SRC.glob("*.webp")):
    shutil.copyfile(path, OUT / path.name)
    ids.append(path.stem)

lines = [
    "// Generated by scripts/build-divination-assets.py. Do not edit by hand.",
    "// Tarot card id (as in tarot.ts) to the app's bundled copy of the website's",
    "// card picture, /assets/divination/tarot/<id>.webp.",
    "",
    "export const tarotImages: Record<string, number> = {",
]
for card in ids:
    lines.append(f"  '{card}': require('../../../assets/divination/tarot/{card}.webp'),")
lines += ["};", ""]
MANIFEST.write_text("\n".join(lines))
total = sum((OUT / f"{card}.webp").stat().st_size for card in ids)
print(f"{len(ids)} cards, {total / 1024 / 1024:.1f} MB")
