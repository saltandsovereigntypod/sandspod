// Copies the website's Traditional Library (js/traditional-library.js) into the
// app as typed data, so the app's Library shows exactly what the website shows.
// Run from app/: node scripts/sync-traditional-library.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(resolve(here, '../../js/traditional-library.js'), 'utf8');
const context = {};
vm.runInNewContext(`${source}\nthis.TraditionalLibrary = TraditionalLibrary;`, context);
const data = JSON.parse(JSON.stringify(context.TraditionalLibrary));

const out = `// Generated by scripts/sync-traditional-library.mjs from js/traditional-library.js.
// Do not edit by hand: change the website file and run the script again.
import type { TraditionalLibraryData } from './types';

export const TRADITIONAL_LIBRARY: TraditionalLibraryData = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(resolve(here, '../src/lib/library/traditionalData.ts'), out);
const counts = Object.entries(data).map(([type, items]) => `${type}: ${Object.keys(items).length}`);
console.log(`Traditional Library synced (${counts.join(', ')})`);
