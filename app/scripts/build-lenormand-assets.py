"""Build the Lenormand pictures for the website and the app.

The 36 cards are the Petit Lenormand printed by Geûens-Seaux of Bruges
between about 1895 and 1901, scanned by the Bibliothèque nationale de France
(Gallica btv1b10529584r) and shared on Wikimedia Commons as public domain;
see ../assets/divination/decks/lenormand/SOURCES.md. Given a folder of the
36 card fronts (01.jpg … 36.jpg, numbered as the cards are, downloaded from
upload.wikimedia.org and kept out of the repo), this

- trims the scanner's margin from each card,
- writes the website's copies, 600 px tall WebP, to
  ../assets/divination/lenormand/<id>.webp (ids as in lenormand.ts),
- packs the app's copies six across and three down on two sheets in
  assets/divination/decks/lenormand/ (an over-the-air update may carry at
  most 1000 files), and
- writes src/lib/divination/oracle/lenormandAssets.ts with each card's place.

Run from app/:  python3 scripts/build-lenormand-assets.py <folder of fronts>   (needs Pillow)
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageChops

APP = Path(__file__).resolve().parent.parent
WEB = APP.parent / "assets" / "divination" / "lenormand"
OUT = APP / "assets" / "divination" / "decks" / "lenormand"
MANIFEST = APP / "src" / "lib" / "divination" / "oracle" / "lenormandAssets.ts"
CELL_W, CELL_H, COLS, ROWS = 340, 500, 6, 3
WEB_H = 600

src = Path(sys.argv[1])
names = re.findall(r"^    name: '([^']+)',", (APP / "src" / "lib" / "divination" / "oracle" / "lenormand.ts").read_text(), re.M)
assert len(names) == 36, len(names)
ids = [f"{i + 1:02d}-" + re.sub(r"[^a-z]+", "-", n.lower()) for i, n in enumerate(names)]


def trim(im: Image.Image) -> Image.Image:
    """Cut away the scanner's background round the card: the bounding box of what differs from the corner colour."""
    rgb = im.convert("RGB")
    bg = Image.new("RGB", rgb.size, rgb.getpixel((2, 2)))
    diff = ImageChops.difference(rgb, bg).convert("L").point(lambda v: 255 if v > 28 else 0)
    box = diff.getbbox()
    if not box:
        return rgb
    l, t, r, b = box
    # Keep it only if it's plausibly the card (not a speck), and inset a hair to lose the edge shadow.
    if (r - l) < rgb.width * 0.7 or (b - t) < rgb.height * 0.7:
        return rgb
    pad = 4
    return rgb.crop((l + pad, t + pad, r - pad, b - pad))


WEB.mkdir(parents=True, exist_ok=True)
OUT.mkdir(parents=True, exist_ok=True)
for stale in OUT.glob("*.webp"):
    stale.unlink()

cards = []
for k, card_id in enumerate(ids):
    im = trim(Image.open(src / f"{k + 1:02d}.jpg"))
    w = round(im.width * WEB_H / im.height)
    im.resize((w, WEB_H), Image.LANCZOS).save(WEB / f"{card_id}.webp", quality=82, method=6)
    cards.append(im)

per = COLS * ROWS
sheets = []
for s in range(0, len(cards), per):
    sheet = Image.new("RGB", (COLS * CELL_W, ROWS * CELL_H), (233, 224, 204))
    for i, im in enumerate(cards[s:s + per]):
        sheet.paste(im.resize((CELL_W, CELL_H), Image.LANCZOS), ((i % COLS) * CELL_W, (i // COLS) * CELL_H))
    name = f"sheet-{len(sheets) + 1}.webp"
    sheet.save(OUT / name, quality=82, method=6)
    sheets.append(name)

lines = [
    "// Generated by scripts/build-lenormand-assets.py. Do not edit by hand.",
    "// Lenormand card id (as in lenormand.ts) to its sheet and place: the app bundles",
    "// the website's /assets/divination/lenormand/<id>.webp packed onto two sheets.",
    "",
    f"export const LENORMAND_SHEET = {{ cols: {COLS}, rows: {ROWS}, cellWidth: {CELL_W}, cellHeight: {CELL_H} }} as const;",
    "",
    "const sheets: number[] = [",
    *[f"  require('../../../../assets/divination/decks/lenormand/{n}')," for n in sheets],
    "];",
    "",
    "export type SheetPlace = { sheet: number; col: number; row: number };",
    "",
    "export const lenormandImages: Record<string, SheetPlace> = {",
]
for k, card_id in enumerate(ids):
    i = k % per
    lines.append(f"  '{card_id}': {{ sheet: sheets[{k // per}], col: {i % COLS}, row: {i // COLS} }},")
lines += ["};", ""]
MANIFEST.write_text("\n".join(lines))
total = sum((OUT / n).stat().st_size for n in sheets)
web = sum(p.stat().st_size for p in WEB.glob("*.webp"))
print(f"{len(ids)} cards: {len(sheets)} app sheets ({total / 1024 / 1024:.1f} MB), website {web / 1024 / 1024:.1f} MB")
