#!/usr/bin/env node
// Writes src/lib/calendars/registry.ts: a static import of every traditional
// calendar in src/lib/calendars/<id>.ts (each `export const <ID>_CALENDAR:
// CalendarDef`), so the bundler can see them all. The moon's months are
// imported directly by index.ts and left out here. Run again whenever a
// calendar file is added, renamed or removed:
//
//   node scripts/gen-calendars-index.mjs
//
// Calendars come in a fixed order (Roman, Attic, Icelandic, Kemetic, Hindu,
// Slavic, Coligny), then any others by file name. A file without
// `export const …_CALENDAR` is skipped with a warning.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src/lib/calendars');
const out = join(dir, 'registry.ts');

const ORDER = ['roman', 'attic', 'icelandic', 'kemetic', 'hindu', 'slavic', 'coligny'];
const NOT_CALENDARS = new Set(['types.ts', 'index.ts', 'registry.ts', 'moon.ts']);

const rank = (file) => {
  const i = ORDER.indexOf(file.replace(/\.ts$/, ''));
  return i === -1 ? ORDER.length : i;
};
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.startsWith('_') && !NOT_CALENDARS.has(f))
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

const entries = [];
for (const file of files) {
  const text = readFileSync(join(dir, file), 'utf8');
  const name = /export const ([A-Z0-9_]+_CALENDAR)\b/.exec(text)?.[1];
  if (!name) {
    console.warn(`skipped ${file}: no "export const …_CALENDAR"`);
    continue;
  }
  entries.push({ file, name });
}

const lines = [
  '// Generated by scripts/gen-calendars-index.mjs. Do not edit by hand:',
  '// add a calendar file here and run `node scripts/gen-calendars-index.mjs`.',
  '',
  "import type { CalendarDef } from './types.ts';",
  '',
  ...entries.map(({ file, name }) => `import { ${name} } from './${file}';`),
  '',
  '/** The traditional calendars, in display order (the moon is added by index.ts). */',
  'export const TRADITIONAL_CALENDARS: CalendarDef[] = [',
  ...entries.map(({ name }) => `  ${name},`),
  '];',
  '',
];

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${entries.length} calendars to src/lib/calendars/registry.ts${entries.length ? `: ${entries.map((e) => e.file).join(', ')}` : ''}`);
