#!/usr/bin/env node
// Writes src/lib/journeys/registry.ts: a static import of every journey in
// src/lib/journeys/data/*.ts (each `export const JOURNEY: Journey`), so the
// bundler can see them all. Run again whenever a journey file is added,
// renamed or removed:
//
//   node scripts/gen-journeys-index.mjs
//
// Files are sorted by name; each import is aliased by the journey's id
// (deity-hekate → DEITY_HEKATE). A file without `export const JOURNEY` is
// skipped with a warning.
//
// It also writes src/lib/journeys/catalog.ts: each journey's id, kind, paths,
// deity, title and summary, so a list (the website's) can show every journey
// without loading them all.

import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src/lib/journeys/data');
const out = join(root, 'src/lib/journeys/registry.ts');

const files = readdirSync(dataDir)
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.startsWith('_'))
  .sort();

const entries = [];
const seen = new Set();
for (const file of files) {
  const text = readFileSync(join(dataDir, file), 'utf8');
  if (!/export const JOURNEY\b/.test(text)) {
    console.warn(`skipped ${file}: no "export const JOURNEY"`);
    continue;
  }
  const id = /\bid:\s*['"]([^'"]+)['"]/.exec(text)?.[1] ?? file.replace(/\.ts$/, '');
  let alias = id.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^(\d)/, '_$1');
  while (seen.has(alias)) alias += '_';
  seen.add(alias);
  entries.push({ file, alias });
}

const lines = [
  '// Generated by scripts/gen-journeys-index.mjs. Do not edit by hand:',
  '// add a file to ./data and run `node scripts/gen-journeys-index.mjs`.',
  '',
  "import type { Journey } from './types.ts';",
  '',
  ...entries.map(({ file, alias }) => `import { JOURNEY as ${alias} } from './data/${file}';`),
  '',
  '/** Every journey, in file order (paths and deities sorted by file name). */',
  'export const JOURNEYS: Journey[] = [',
  ...entries.map(({ alias }) => `  ${alias},`),
  '];',
  '',
];

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${entries.length} journeys to src/lib/journeys/registry.ts`);

// The catalog, read from the journeys themselves (Node strips the types).
const read = `
  const { JOURNEYS } = await import(${JSON.stringify(pathToFileURL(out).href)});
  const pick = ({ id, kind, paths, deityRef, title, summary }) => (deityRef ? { id, kind, paths, deityRef, title, summary } : { id, kind, paths, title, summary });
  process.stdout.write(JSON.stringify(JOURNEYS.map(pick)));
`;
const catalog = JSON.parse(
  execFileSync(process.execPath, ['--experimental-strip-types', '--disable-warning=ExperimentalWarning', '--disable-warning=MODULE_TYPELESS_PACKAGE_JSON', '--input-type=module', '-e', read], { encoding: 'utf8', maxBuffer: 1 << 26 }),
);
writeFileSync(
  join(root, 'src/lib/journeys/catalog.ts'),
  [
    '// Generated by scripts/gen-journeys-index.mjs. Do not edit by hand:',
    '// run `node scripts/gen-journeys-index.mjs` after changing a journey.',
    '// Each journey in a few words, for lists that load journeys one at a time.',
    '',
    "import type { JourneyLike } from './lookup.ts';",
    '',
    `export const JOURNEY_CATALOG: JourneyLike[] = ${JSON.stringify(catalog, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${catalog.length} journeys to src/lib/journeys/catalog.ts`);
