// The premade bath mixes: thirty spiritual and comfort baths, each with its
// intention, ingredients and amounts, how to prepare it, when it suits, words
// to speak, what to do afterwards and how long to stay. What is modern and
// what is old is said plainly: bath-magic as it is practised now draws on
// European herb lore, folk bathing customs, Hoodoo and Spiritualist "spiritual
// baths" (a living tradition: these are general modern mixes, not its
// recipes), and aromatherapy. Nothing here is medical treatment.
// The warnings are never written here: lib/craft/bath/safety.ts works them out
// from the ingredients.

import type { BathIngredient } from './safety.ts';

export type BathMethod = 'sachet' | 'infusion' | 'loose' | 'salts';

export type BathMix = {
  id: string;
  title: string;
  /** The timing advisor's intent key (love, money, protection, banishing, healing, cleansing, divination, communication, courage, ancestors, endings, beginnings, peace). */
  intent: string;
  /** One line: what it is for. */
  intention: string;
  group: 'everyday' | 'moon' | 'season' | 'gentle';
  ingredients: BathIngredient[];
  method: BathMethod;
  /** What is particular about preparing this one. */
  prep: string;
  when: { moon: string; day: string; hour: string };
  words: string;
  /** What to do with the water and herbs beyond the usual (the rest follows from the ingredients). */
  after: string;
  minutes: number;
  candle?: string;
  /** Where it comes from and how sure that is. */
  note?: string;
  /** Holy pages (lib/holy refs) it is the kit's bath for. */
  kits?: string[];
  /** Made by you. */
  own?: boolean;
};

const H = (key: string) => `traditional/herb/${key}`;
const C = (key: string) => `traditional/crystal/${key}`;
const salt = (name: string, amount: string, optional = false): BathIngredient => ({ name, amount, kind: 'salt', ...(optional ? { optional } : {}) });
const herb = (name: string, amount: string, key?: string, optional = false): BathIngredient => ({ name, amount, kind: 'herb', ...(key ? { ref: H(key) } : {}), ...(optional ? { optional } : {}) });
const flower = (name: string, amount: string, key?: string, optional = false): BathIngredient => ({ name, amount, kind: 'flower', ...(key ? { ref: H(key) } : {}), ...(optional ? { optional } : {}) });
const carrier = (name: string, amount: string, optional = false): BathIngredient => ({ name, amount, kind: 'carrier', ...(optional ? { optional } : {}) });
const stone = (name: string, key: string, optional = true): BathIngredient => ({ name, amount: 'one small stone', kind: 'crystal', ref: C(key), ...(optional ? { optional } : {}) });
const other = (name: string, amount: string, optional = false): BathIngredient => ({ name, amount, kind: 'other', ...(optional ? { optional } : {}) });

const SEA = () => salt('Sea salt', '1/2 cup (about 120 g)');
