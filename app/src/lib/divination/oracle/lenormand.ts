// The Petit Lenormand: thirty-six cards, numbered and named as the German
// "Game of Hope" of about 1799 first laid them out, each with a small
// playing card set into its corner. The pictures are a Belgian printing of
// the 1890s (Geûens-Seaux, Bruges; see assets/divination/decks/lenormand).
// Lenormand is read in pairs and lines rather than card by card: the first
// card of a pair names the matter, the second describes it, so each card
// has a meaning as the subject and as the modifier. Names are unique across
// every deck in the app, so a drawn card saves by its name alone. Pure data.

import type { ThreeWords } from '../deep/types.ts';
import type { Meaning } from '../tarot.ts';

export type LenormandCard = {
  /** Stable id and the picture's name: "01-rider". */
  id: string;
  /** 1 to 36, as printed on the card. */
  number: number;
  /** As saved in a reading: "Rider", "Clover". */
  name: string;
  /** The playing card in its corner: "9♥". */
  playing: string;
  /** That playing card in words: "Nine of Hearts". */
  playingName: string;
  words: ThreeWords;
  /** Its meaning in a few words and two or three sentences, for the draw. */
  meaning: Meaning;
  /** First in a pair: what it names. A short noun phrase ("news", "a journey"). */
  noun: string;
  /** Second in a pair: how it colours the card before it. A short describing phrase ("quick", "far away"). */
  adjective: string;
  /** As the subject, in a sentence or two. */
  subject: string;
  /** As the modifier, in a sentence or two. */
  modifier: string;
  /** What it says about when, as many readers take it today. */
  timing: string;
  /** What the Bruges card shows. */
  image: string;
  /** The card as a house in the Grand Tableau: what a card falling on it is about. */
  house: string;
  question: string;
};

