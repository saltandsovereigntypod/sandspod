export const LENORMAND: LenormandCard[] = ROWS.map((r, i) => ({
  ...r,
  id: `${String(i + 1).padStart(2, '0')}-${slug(r.name)}`,
  number: i + 1,
  playingName: playingName(r.playing),
}));

export const lenormandCard = (name: string): LenormandCard | null => LENORMAND.find((c) => c.name === name) ?? null;
export const lenormandById = (id: string): LenormandCard | null => LENORMAND.find((c) => c.id === id) ?? null;

/** The suits of the playing cards, as French cartomancy reads them. */
export const SUIT_SENSE: Record<string, string> = {
  Hearts: 'hearts are love, home and happy news',
  Diamonds: 'diamonds are money, business and messages',
  Clubs: 'clubs are work, worry and everyday trouble',
  Spades: 'spades are hardship, serious matters and endings',
};

/** The playing card in its corner, and what readers do with it. */
export function playingCardText(card: LenormandCard): string {
  const suit = card.playingName.split(' of ')[1];
  return `The ${card.playingName}. In the old French way of reading a pack, ${SUIT_SENSE[suit]}. Lenormand readers use the inserts to group cards by suit, to read the court cards as people, or to lay the deck as playing cards; many leave them aside.`;
}

