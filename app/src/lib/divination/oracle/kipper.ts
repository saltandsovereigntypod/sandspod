export const KIPPER: KipperCard[] = ROWS.map((r, i) => ({ ...r, id: `${String(i + 1).padStart(2, '0')}-${slug(r.name)}`, number: i + 1 }));

export const kipperCard = (name: string): KipperCard | null => KIPPER.find((c) => c.name === name) ?? null;
export const kipperById = (id: string): KipperCard | null => KIPPER.find((c) => c.id === id) ?? null;

