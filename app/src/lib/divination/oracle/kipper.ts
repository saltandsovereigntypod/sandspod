// The Kipper cards: thirty-six German fortune-telling cards, first sold in
// Munich around 1890 and named for a Berlin card-reader, Susanne Kipper,
// of whom little is known. Where Lenormand speaks in symbols, Kipper speaks
// in people and situations: the two main persons, good and false people,
// letters, money, the house and the living room. No complete public-domain
// printing could be found, so the app draws each card itself: its number,
// its name, and its German name. Names are unique across every deck in the
// app, so a drawn card saves by its name alone. Pure data.

import type { ThreeWords } from '../deep/types.ts';
